def verse_message(verse: dict, sources: list[dict]) -> str:
    """The user turn: the verse exactly as stored, its reference, and the verse's stored
    Quranic sources (context.py), each with the id the model cites (Q1, Q2...)."""
    lines = [f"الآية: ﴿{verse['text']}﴾",
             f"[سورة {verse['surah_name']}، رقم السورة {verse['surah_number']}، الآية {verse['ayah_number']} — رواية حفص]",
             "", "حزمة المصادر القرآنية لهذه الآية (من منصة آفاق):"]
    if not sources:
        lines.append("(لا توجد مصادر مخزنة لهذه الآية بعد.)")
    for s in sources:
        lines += ["", f"[{s['id']}] {s['title']} — {s['kind_label']}{' (مقتطع)' if s['truncated'] else ''}", s["text"]]
    lines += ["", "ابدأ البحث وفق المنهجية أعلاه، وأخرج النتيجة بصيغة JSON المطلوبة."]
    return "\n".join(lines)
